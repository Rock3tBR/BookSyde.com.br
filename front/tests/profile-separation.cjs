const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const read = (name) => fs.readFileSync(path.join(root, name), 'utf8');
const preferences = read('src/pages/conta.tsx');
const profile = read('src/pages/meu-perfil.tsx');
const header = read('src/components/SiteHeader.tsx');
const routes = read('src/routeTree.gen.ts');
const access = read('src/lib/access.ts');
const migration = read('supabase/migrations/20260916180000_private_profile_contacts.sql');
const types = read('src/integrations/supabase/types.ts');
assert(!preferences.includes('<TabsContent value="profile"'), 'Profile tab must not exist in preferences');
assert(!preferences.includes('<TabsContent value="security"'), 'Password tab must not exist in preferences');
assert(preferences.includes('.update(preferences).eq("id", user!.id)'), 'Existing nickname must be untouched on preference saves');
assert(preferences.includes('title="Cor do sistema"') && preferences.indexOf('title="Cor do sistema"') > preferences.indexOf('value="catalog"'), 'Theme is under page/catalog appearance');
assert(profile.includes('supabase.auth.updateUser({ password: newPassword })'), 'Profile must update password through auth');
assert(profile.includes('profile_contacts') && profile.includes('AvatarEditor'), 'Profile must own phone and avatar');
assert(header.includes('Meu perfil') && header.includes('goProfile'), 'Profile must be reachable from header');
assert(header.includes('Personalização'), 'Personalization must remain in header');
assert(routes.includes("'/meu-perfil': typeof MeuPerfilRoute") && routes.includes('MeuPerfilRoute: MeuPerfilRoute'), 'Profile route must be registered');
assert(access.includes('pathname === "/meu-perfil"'), 'Editora must be able to open own profile');
assert(migration.includes('enable row level security') && migration.includes('auth.uid()') && migration.includes('to authenticated'), 'Phone RLS must restrict access');
assert(types.includes('profile_contacts: {'), 'Supabase types must include new table');
console.log('Profile split, header, route, data model and RLS: 11 checks passed.');
